#!/bin/zsh
# Rebuilds every generated icon from the SVGs and copies them to the apps that use them. Needs rsvg-convert
# (brew install librsvg). Run make-svgs.py first when the drawings change, then commit everything this touches.
set -euo pipefail
HERE="${0:A:h}"
ROOT="${HERE:h:h}"
cd "$HERE"
command -v rsvg-convert >/dev/null || { echo "!! rsvg-convert not found: brew install librsvg" >&2; exit 1; }

WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
png() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

echo "==> macOS .icns"
for app in novahelm novaguard novalink novagear novacompute; do
  set="$WORK/$app.iconset"
  mkdir -p "$set"
  for size in 16 32 128 256 512; do
    png "$app.svg" $size "$set/icon_${size}x${size}.png"
    png "$app.svg" $((size * 2)) "$set/icon_${size}x${size}@2x.png"
  done
  iconutil -c icns "$set" -o "$app.icns"
done

echo "==> Windows .ico and the Linux icon"
for app in novalink novagear; do
  for size in 16 24 32 48 64 256; do png "$app-tile.svg" $size "$WORK/$app-$size.png"; done
  python3 make-ico.py "$app.ico" "$WORK/$app"-{16,24,32,48,64,256}.png
done
cp "$WORK/novagear-256.png" novagear-256.png

echo "==> Web icons"
web() { # web APP DIR: favicon, home-screen icon and the manifest's icons
  cp "$1-tile.svg" "$2/favicon.svg"
  png "$1-square.svg" 180 "$2/apple-touch-icon.png"
  png "$1-square.svg" 192 "$2/icon-192.png"
  png "$1-square.svg" 512 "$2/icon-512.png"
}
mkdir -p "$ROOT/web/public" "$ROOT/novaguard/dashboard/public"
web novahelm "$ROOT/web/public"
web novahelm "$ROOT/site/public"
web novaguard "$ROOT/novaguard/dashboard/public"
cp novagear-tile.svg "$ROOT/novagear/crates/agent/panel/favicon.svg"
png novagear-square.svg 180 "$ROOT/novagear/crates/agent/panel/apple-touch-icon.png"
# The accounts Worker serves HTML strings, so its favicon travels inline.
print -r -- "// Generated by brand/icons/build-icons.sh from novahelm-tile.svg. Do not edit.
export const FAVICON =
  \"data:image/svg+xml;base64,$(base64 -i novahelm-tile.svg | tr -d '\n')\";" > "$ROOT/accounts/src/favicon.ts"

echo "==> preview.png"
x=0; images=""
for app in novahelm novaguard novalink novagear novacompute; do
  png "$app.svg" 256 "$WORK/$app-preview.png"
  images+="<image href=\"file://$WORK/$app-preview.png\" x=\"$x\" y=\"16\" width=\"256\" height=\"256\"/>"
  x=$((x + 272))
done
print -r -- "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$((x + 16))\" height=\"288\">$images</svg>" > "$WORK/preview.svg"
rsvg-convert --unlimited "$WORK/preview.svg" -o preview.png
echo "==> Done"
